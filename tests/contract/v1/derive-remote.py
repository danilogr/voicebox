#!/usr/bin/env python3
"""Derive schema.remote.sql from schema.sql by stripping local-only lines.

A line is local-only iff it carries SQL (a column, a statement) followed by
a trailing comment that is exactly `-- LOCAL` or starts with `-- LOCAL`
followed by a space or a colon (e.g. `-- LOCAL: reason`). That is the one
spelling the tag recognises; every such line is dropped from the remote
output.

Any other trailing comment on a SQL line that contains the word "local" in
some other form (wrong case, no space after `--`, the word embedded
mid-sentence) is treated as a malformed tag, not a normal comment, and
fails the build. The whole point of the tag is that a column is local
until someone writes it down correctly, so a near-miss on a real
definition must stop the build rather than let an unrecognised column
travel to schema.remote.sql unflagged.

Whole-line comments carrying no SQL (file and section headers, this
docstring's own prose if it were inline) are documentation, not tag sites,
and are copied through unchecked.
"""
import re
import sys
from pathlib import Path

SCHEMA_PATH = Path(__file__).parent / "schema.sql"
OUTPUT_PATH = Path(__file__).parent / "schema.remote.sql"

HEADER = (
    "-- GENERATED by derive-remote.py from schema.sql. Do not edit by hand:\n"
    "-- edit schema.sql and its `-- LOCAL` tags, then regenerate.\n"
)

VALID_TAG = re.compile(r"^-- LOCAL(\s|:|$)")
MENTIONS_LOCAL = re.compile(r"\blocal\b", re.IGNORECASE)


class MalformedTag(SystemExit):
    def __init__(self, lineno: int, line: str):
        super().__init__(
            f"derive-remote.py: malformed LOCAL tag at schema.sql:{lineno}\n"
            f"  {line}\n"
            f"expected the trailing comment to start with exactly '-- LOCAL' "
            f"(one space, that case), followed by nothing, a space, or a colon."
        )


def split_trailing_comment(line: str) -> tuple[str, str | None]:
    """Split a SQL line into (code, comment). `comment` includes the
    leading `--` and is stripped of surrounding whitespace; it is None
    when the line has no line comment. This schema never puts `--` inside
    a string literal, so a plain substring search is exact."""
    idx = line.find("--")
    if idx == -1:
        return line, None
    return line[:idx], line[idx:].strip()


def fix_dangling_commas(lines: list[str]) -> list[str]:
    """Dropping the last local column in a table leaves the previous
    column's trailing comma with nothing after it but the closing paren;
    SQLite and D1 both reject that. Column order in schema.sql is free to
    change, so this looks at the code (never the comment) on each line to
    find a comma immediately followed - skipping blank lines - by a line
    whose code starts with `)`, and removes just that comma."""
    codes = [split_trailing_comment(line)[0].rstrip() for line in lines]
    fixed = list(lines)
    for i, code in enumerate(codes):
        if not code.endswith(","):
            continue
        j = i + 1
        while j < len(codes) and codes[j].strip() == "":
            j += 1
        if j < len(codes) and codes[j].lstrip().startswith(")"):
            line = fixed[i]
            line_code, comment = split_trailing_comment(line)
            trailing_ws = line_code[len(code):]
            new_code = code[:-1]  # drop the comma
            fixed[i] = new_code + trailing_ws + (comment or "")
    return fixed


def derive(text: str) -> str:
    out_lines: list[str] = []
    for lineno, line in enumerate(text.splitlines(), start=1):
        code, comment = split_trailing_comment(line)
        if comment is None:
            out_lines.append(line)
            continue
        if not code.strip():
            # Whole-line comment: documentation, not a tag site. Passed
            # through as-is even if it discusses the tag by name.
            out_lines.append(line)
            continue
        if VALID_TAG.match(comment):
            continue  # local-only line: dropped from the remote schema
        if MENTIONS_LOCAL.search(comment):
            raise MalformedTag(lineno, line)
        out_lines.append(line)
    out_lines = fix_dangling_commas(out_lines)
    body = "\n".join(out_lines)
    # Cosmetic: collapse the runs of blank lines that stripped columns leave
    # behind, so schema.remote.sql reads like hand-written DDL.
    body = re.sub(r"\n{3,}", "\n\n", body)
    return HEADER + body + "\n"


def main() -> None:
    text = SCHEMA_PATH.read_text()
    remote = derive(text)
    OUTPUT_PATH.write_text(remote)
    print(f"wrote {OUTPUT_PATH} ({len(remote.splitlines())} lines)")


if __name__ == "__main__":
    main()
